export const HOIKU_GUIDELINE_REFERENCE = {
  title: "保育所保育指針",
  agency: "こども家庭庁",
  sourceUrl: "https://www.cfa.go.jp/policies/hoiku",
};

export function buildHoikuGuidelinePromptBlock(kind = "common") {
  const base = [
    "【保育所保育指針の参照観点】",
    "保育所保育指針は、出力を水増しするためではなく、学生の観察・省察を見直す観点として扱います。",
    "重視する観点: 子どもの最善の利益、養護と教育の一体性、子どもの主体的な活動、環境を通して行う保育、発達過程と個人差への配慮、家庭・地域との連携。",
    "3歳以上児の保育内容では、健康・人間関係・環境・言葉・表現の5領域を参照します。ただし、学生入力に根拠がない領域を勝手に当てはめたり、活動の効果を断定したりしないでください。",
    "幼児期の終わりまでに育ってほしい姿は、到達目標や子どもを評価する項目として使わず、保育者が援助や環境を振り返る視点として扱ってください。",
    "出力本文で条文名や制度説明を多用せず、学生が提出前に考え直せる自然な表現にしてください。根拠が不足する場合は、本文で断定せずchecksに確認の問いとして残してください。",
  ];

  if (kind === "plan") {
    return [
      ...base,
      "指導案では、ねらい、環境構成、展開、安全面、個別配慮を、保育所保育指針の観点と照らして確認します。ただし、活動内容・材料・場所・人数・手順は学生入力にある範囲だけで扱います。",
      "5領域との関連は、学生の活動案やねらいから読み取れる範囲に限り、『関連が考えられる』『確認したい』のように開いた表現で扱ってください。",
    ].join("\n");
  }

  if (kind === "diary") {
    return [
      ...base,
      "実習日誌では、子どもの姿、環境、実習生の関わり、明日の観察視点を振り返るための観点として扱います。学生メモにない発達効果や内面を、指針を理由に補完しないでください。",
      "5領域や保育所保育指針とのつながりは、本文で断定的に書くのではなく、学生本人が見直す問いとしてchecksに残すことを基本にしてください。",
      "学生メモに具体的な子どもの姿が少ない場合は、領域名を当てはめず『どの姿がどの観点とつながるか確認する』という問いに留めてください。",
      "考察では、子どもを評価するのではなく、保育者の援助や環境をどう見直せるかに寄せてください。",
    ].join("\n");
  }

  return base.join("\n");
}
